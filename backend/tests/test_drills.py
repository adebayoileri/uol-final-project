def test_a_partly_clued_lesson_is_not_told_to_open_itself_again(client, db_session):
    """The clue pass ran and rejected some descriptions, so `clues_json` is set
    and `ensure_clues` will never retry it. Telling the learner to open the
    lesson would be advice that provably cannot change anything — the second
    dead end this feature has had to avoid."""
    thin = json.dumps({
        "clues": {"Concept 0": "A description of the situation in case zero and what follows from it."}
    })
    course = _seed(db_session, lesson_contents=[_content(6)], clues=[thin])
    drills = {d["kind"]: d for d in client.get(f"/courses/{course.id}/drills").json()["drills"]}

    assert drills["listen"]["available"] is False
    assert drills["listen"]["item_count"] == 1
    assert "open a lesson" not in drills["listen"]["reason"]
    assert "backfill" in drills["listen"]["reason"]


def test_the_listen_endpoint_reveals_nothing_but_the_options(client, db_session):
    """End-to-end: strip the options from the payload and no concept name should
    remain anywhere in it — not in the id, not in the lesson title, nowhere."""
    course = _seed(db_session, lesson_contents=[_content(6)])
    names = _concept_names(course, db_session)

    with patch(TTS_PATCH, return_value=b"RIFFfake"):
        body = client.get(f"/courses/{course.id}/drills/listen?n=6").json()

    assert body["items"]
    for item in body["items"]:
        rest = json.dumps({k: v for k, v in item.items() if k != "options"})
        for name in names:
            assert name.casefold() not in rest.casefold()


