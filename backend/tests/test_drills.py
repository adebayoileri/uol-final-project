def _content(n_concepts: int, steps: int = 4) -> str:
    """A lesson body, written the way the enrichment prompt actually produces one.

    Note what the definition does NOT do: name its own concept. An earlier
    version of this fixture defined `Concept {i}` as "…definition for concept
    {i}…", which is precisely the property that broke the choice drills — the
    prompt text contained the answer. The fixture encoded the bug, so no test
    could have caught it; that is Defect 8 in the report, twice over now.
    """
    return json.dumps(
        {
            "key_concepts": [
                {
                    "name": f"Concept {i}",
                    "definition": (
                        f"The mechanism that governs case {i}, the conditions "
                        "under which it applies and why it behaves that way."
                    ),
                    "example": f"example_{i}()" if i % 2 == 0 else "",
                }
                for i in range(n_concepts)
            ],
            # Bodies must differ once the ordinal marker is stripped, or the steps
            # become indistinguishable and the ordering drill is unsolvable.
            "worked_example": "\n".join(
                f"Step {i}: do thing number {i}." for i in range(steps)
            ),
            "common_pitfalls": [],
            "practice_prompts": [],
        }
    )


def _clues(n_concepts: int) -> str:
    """Clues for a lesson body from `_content`, in the shape `Lesson.clues` reads."""
    return json.dumps({
        "clues": {
            f"Concept {i}": (
                f"A description of the situation in case {i} and what follows from "
                "it, phrased so the listener has to recognise it rather than hear it."
            )
            for i in range(n_concepts)
        }
    })


def _lesson_clues(clues, index: int, content: str | None) -> str | None:
    """The stored clue set for one seeded lesson.

    Generated by a separate pass from enrichment, so it is absent whenever the
    content is. `clues` overrides that per lesson, which is how the tests model a
    lesson that has been enriched but has not had its clues written yet.
    """
    if clues is not None:
        return clues[index]
    if not content:
        return None
    return _clues(len(json.loads(content)["key_concepts"]))


