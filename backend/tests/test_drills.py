def _seed(
    db_session,
    *,
    lesson_contents,
    clues=None,
    category="Programming",
    goal="Learn things",
    title="A Course",
):
    course = Course(
        user_id=TEST_USER_ID,
        goal=goal, duration="short_term", category=category, title=title, description="d"
    )
    db_session.add(course)
    db_session.flush()
    module = Module(course_id=course.id, order_index=0, title="M", description="d")
    db_session.add(module)
    db_session.flush()
    for i, content in enumerate(lesson_contents):
        db_session.add(
            Lesson(
                module_id=module.id,
                order_index=i,
                title=f"Lesson {i}",
                description="Prose summary.",
                duration_minutes=20,
                content_json=content,
                clues_json=_lesson_clues(clues, i, content),
            )
        )
    db_session.commit()
    db_session.refresh(course)
    return course


