def _concept_names(course, db_session) -> set[str]:
    return {
        c.name for c in collect_concepts(load_course_lessons(course.id, db_session))
    }


def test_listen_speaks_the_clue_and_never_the_definition(db_session):
    """The definition is the one text that must not be spoken: it names its term."""
    import random

    course = _seed(db_session, lesson_contents=[_content(6)])
    lessons = load_course_lessons(course.id, db_session)
    concepts = collect_concepts(lessons)

    items = build_listen(concepts, 6, random.Random(0))
    assert items

    clues = {c.clue for c in concepts}
    definitions = {c.definition for c in concepts}
    for item in items:
        assert item["speak"] in clues
        assert item["speak"] not in definitions


def test_no_spoken_clue_contains_any_concept_name(db_session):
    """The property the whole feature exists to guarantee, asserted against real
    generated items rather than against the validator's own unit tests."""
    import random

    course = _seed(db_session, lesson_contents=[_content(6), _content(6)])
    lessons = load_course_lessons(course.id, db_session)
    names = _concept_names(course, db_session)

    for item in build_listen(collect_concepts(lessons), 12, random.Random(3)):
        spoken = item["speak"].casefold()
        for name in names:
            assert name.casefold() not in spoken, f"{name!r} is spoken in its own clue"


